					(string) ( $row['id'] ?? '' ),
					(string) ( $row['article'] ?? '' ),
					(string) ( $row['label'] ?? '' ),
					(string) ( $row['status'] ?? '' ),
					(string) ( $row['evidence'] ?? '' ),
					(string) ( $row['detail'] ?? '' ),
					(string) ( $row['control'] ?? '' ),
					(string) ( $row['link'] ?? '' ),
				)
			);
		}

		return implode( "\n", $lines ) . "\n";
	}

	/**
	 * @param list<string> $cols Columns.
	 */
	public static function csv_line( array $cols ): string {
		$out = array();
		foreach ( $cols as $col ) {
			$col = (string) $col;
			if ( false !== strpos( $col, '"' ) || false !== strpos( $col, ',' ) || false !== strpos( $col, "\n" ) ) {
				$col = '"' . str_replace( '"', '""', $col ) . '"';
			}
			$out[] = $col;
		}

		return implode( ',', $out );
	}

