	public static function csv_for_roster( ?array $rows = null ): string {
		$rows   = is_array( $rows ) ? $rows : self::readiness_roster();
		$lines  = array();
		$lines[] = self::csv_line(
			array(
				'framing',
				'id',
				'article',
				'label',
				'status',
				'evidence',
				'detail',
				'control',
				'link',
			)
		);
		foreach ( $rows as $row ) {
			$lines[] = self::csv_line(
				array(
