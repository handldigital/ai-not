	/**
	 * Effective obligation table after the public filter.
	 *
	 * @return array{
	 *   shipped:string,
	 *   items:list<array{id:string,article:string,label:string,summary:string,control:string}>
	 * }
	 */
	public static function obligations(): array {
		$bundled = self::bundled_obligations();
		/**
		 * Filter the AI Act deployer obligation inventory table.
		 *
		 * @param array<string,mixed> $table Obligation table.
		 */
		$filtered = apply_filters( self::FILTER_OBLIGATIONS, $bundled );

		return self::sanitize_obligations( $filtered, $bundled );
	}

	/**
	 * @param mixed               $raw      Filtered value.
	 * @param array<string,mixed> $fallback Bundled fallback.
	 * @return array{
	 *   shipped:string,
	 *   items:list<array{id:string,article:string,label:string,summary:string,control:string}>
	 * }
	 */
	public static function sanitize_obligations( $raw, ?array $fallback = null ): array {
		$fallback = is_array( $fallback ) ? $fallback : self::bundled_obligations();
		if ( ! is_array( $raw ) ) {
			return $fallback;
		}

		$shipped = isset( $raw['shipped'] ) ? self::sanitize_day_key( (string) $raw['shipped'] ) : '';
		if ( '' === $shipped ) {
			$shipped = self::sanitize_day_key( (string) ( $fallback['shipped'] ?? self::BUNDLED_SHIPPED ) );
		}
		if ( '' === $shipped ) {
			$shipped = self::BUNDLED_SHIPPED;
		}

		$items_raw = isset( $raw['items'] ) && is_array( $raw['items'] ) ? $raw['items'] : array();
		$items     = array();
		$seen      = array();
		foreach ( $items_raw as $item ) {
			if ( ! is_array( $item ) ) {
				continue;
			}
			$id = isset( $item['id'] ) ? sanitize_key( (string) $item['id'] ) : '';
			if ( '' === $id || isset( $seen[ $id ] ) ) {
				continue;
			}
			$control = isset( $item['control'] ) ? sanitize_key( (string) $item['control'] ) : '';
			if ( '' === $control ) {
				continue;
			}
			$article = isset( $item['article'] ) ? preg_replace( '/[^0-9A-Za-z.\-]/', '', (string) $item['article'] ) : '';
			$label   = isset( $item['label'] ) ? sanitize_text_field( (string) $item['label'] ) : '';
			$summary = isset( $item['summary'] ) ? sanitize_textarea_field( (string) $item['summary'] ) : '';
			if ( '' === $label ) {
				$label = $id;
			}
			$seen[ $id ] = true;
			$items[]     = array(
				'id'      => $id,
				'article' => (string) $article,
				'label'   => $label,
				'summary' => $summary,
				'control' => $control,
			);
		}

		if ( empty( $items ) ) {
			$items = is_array( $fallback['items'] ?? null ) ? $fallback['items'] : array();
		}

		return array(
			'shipped' => $shipped,
			'items'   => $items,
		);
	}

	public static function sanitize_day_key( string $raw ): string {
		$raw = trim( $raw );
		if ( ! preg_match( '/^\d{4}-\d{2}-\d{2}$/', $raw ) ) {
			return '';
		}
		$ts = strtotime( $raw . ' UTC' );
		if ( false === $ts ) {
			return '';
		}

		return gmdate( 'Y-m-d', $ts );
	}

	public static function table_age_ts( ?array $table = null ): int {
		$table = is_array( $table ) ? $table : self::obligations();
		$day   = self::sanitize_day_key( (string) ( $table['shipped'] ?? '' ) );
		if ( '' === $day ) {
			return 0;
		}
		$ts = strtotime( $day . ' UTC' );

		return false === $ts ? 0 : (int) $ts;
	}

	public static function is_table_stale( ?int $now = null, ?array $table = null ): bool {
		$age = self::table_age_ts( $table );
		if ( $age <= 0 ) {
			return true;
		}
		$now = null !== $now && $now > 0 ? $now : ( class_exists( Clock::class, false ) ? Clock::now() : time() );

		return ( $now - $age ) > ( self::STALE_AFTER_DAYS * DAY_IN_SECONDS );
	}

	/**
	 * @return array<string,mixed>
	 */
	public static function current_policy(): array {
		$raw = get_option( Plugin::OPTION_KEY, array() );

		return is_array( $raw ) ? $raw : array();
	}

	/**
	 * Evaluate every obligation against live config (read-only).
	 *
	 * @param array<string,mixed>|null $policy Policy override for tests.
	 * @return list<array{
	 *   id:string,
	 *   article:string,
	 *   label:string,
	 *   summary:string,
	 *   control:string,
	 *   status:string,
	 *   evidence:string,
	 *   detail:string,
	 *   link:string,
	 *   link_label:string
	 * }>
	 */
	public static function readiness_roster( ?array $policy = null ): array {
		$policy = is_array( $policy ) ? $policy : self::current_policy();
		$table  = self::obligations();
		$out    = array();
		foreach ( $table['items'] as $item ) {
			$eval  = self::evaluate_control( (string) $item['control'], $policy );
			$out[] = array(
				'id'         => (string) $item['id'],
				'article'    => (string) $item['article'],
				'label'      => (string) $item['label'],
				'summary'    => (string) $item['summary'],
				'control'    => (string) $item['control'],
				'status'     => (string) $eval['status'],
				'evidence'   => (string) $eval['evidence'],
				'detail'     => (string) $eval['detail'],
				'link'       => (string) $eval['link'],
				'link_label' => (string) $eval['link_label'],
			);
		}

		return $out;
	}

	/**
	 * Obligations with status not_configured.
	 *
	 * @param list<array<string,mixed>>|null $roster Precomputed roster.
	 * @return list<array<string,mixed>>
	 */
	public static function gap_list( ?array $roster = null ): array {
		$roster = is_array( $roster ) ? $roster : self::readiness_roster();
		$gaps   = array();
		foreach ( $roster as $row ) {
			if ( self::STATUS_MISSING === (string) ( $row['status'] ?? '' ) ) {
				$gaps[] = $row;
			}
		}

		return $gaps;
	}

	/**
	 * @return array{met:int,partial:int,not_configured:int,total:int}
	 */
	public static function status_counts( ?array $roster = null ): array {
		$roster = is_array( $roster ) ? $roster : self::readiness_roster();
		$counts = array(
			'met'            => 0,
			'partial'        => 0,
			'not_configured' => 0,
			'total'          => 0,
		);
		foreach ( $roster as $row ) {
			++$counts['total'];
			$status = (string) ( $row['status'] ?? '' );
			if ( self::STATUS_MET === $status ) {
				++$counts['met'];
			} elseif ( self::STATUS_PARTIAL === $status ) {
				++$counts['partial'];
			} else {
				++$counts['not_configured'];
			}
		}

		return $counts;
	}

	/**
	 * @param array<string,mixed> $policy Policy.
	 * @return array{status:string,evidence:string,detail:string,link:string,link_label:string}
	 */
	public static function evaluate_control( string $control, array $policy ): array {
		switch ( $control ) {
			case 'spot_check':
				return self::eval_spot_check();
			case 'activity_log':
				return self::eval_activity_log( $policy );
			case 'log_retention':
				return self::eval_log_retention( $policy );
			case 'policy_gate':
				return self::eval_policy_gate( $policy );
			case 'register':
				return self::eval_register();
			case 'alerts':
				return self::eval_alerts( $policy );
			case 'disclosure':
				return self::eval_disclosure( $policy );
			default:
				return array(
					'status'     => self::STATUS_MISSING,
					'evidence'   => __( 'Unknown control mapping', 'handl-ai-connector-access-control' ),
					'detail'     => __( 'This obligation maps to a control id this build does not evaluate.', 'handl-ai-connector-access-control' ),
					'link'       => self::admin_link( Admin::MENU_SLUG ),
					'link_label' => __( 'AI Access Control', 'handl-ai-connector-access-control' ),
				);
		}
	}

	/**
	 * @return array{status:string,evidence:string,detail:string,link:string,link_label:string}
	 */
	private static function eval_spot_check(): array {
		$link  = self::admin_link( 'handl-aicac-spot-check' );
		$label = __( 'Spot-check', 'handl-ai-connector-access-control' );
		if ( ! class_exists( Spot_Check::class, false ) ) {
			return array(
				'status'     => self::STATUS_MISSING,
				'evidence'   => __( 'Spot-check control', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'Spot-check is not available in this build yet. When shipped, enable human review sampling of allowed AI calls.', 'handl-ai-connector-access-control' ),
				'link'       => self::admin_link( Admin::MENU_SLUG ),
				'link_label' => __( 'AI Access Control', 'handl-ai-connector-access-control' ),
			);
		}
		if ( Spot_Check::is_enabled() ) {
			return array(
				'status'     => self::STATUS_MET,
				'evidence'   => __( 'Spot-check enabled', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'Human review sampling of allowed AI calls is on.', 'handl-ai-connector-access-control' ),
				'link'       => $link,
				'link_label' => $label,
			);
		}

		return array(
			'status'     => self::STATUS_MISSING,
			'evidence'   => __( 'Spot-check', 'handl-ai-connector-access-control' ),
			'detail'     => __( 'Spot-check exists but is off. Enable it to evidence human oversight sampling.', 'handl-ai-connector-access-control' ),
			'link'       => $link,
			'link_label' => $label,
		);
	}

	/**
	 * @param array<string,mixed> $policy Policy.
	 * @return array{status:string,evidence:string,detail:string,link:string,link_label:string}
	 */
	private static function eval_activity_log( array $policy ): array {
		$link  = self::admin_link( Admin::SCREEN_SLUGS['activity'] );
		$label = __( 'Activity', 'handl-ai-connector-access-control' );
		$on    = ! empty( $policy['log_enabled'] ) || ! empty( $policy['audit_only'] );
		if ( $on ) {
			return array(
				'status'     => self::STATUS_MET,
				'evidence'   => __( 'Activity logging', 'handl-ai-connector-access-control' ),
				'detail'     => ! empty( $policy['audit_only'] )
					? __( 'Learn mode is on — AI events are recorded (observation-only).', 'handl-ai-connector-access-control' )
					: __( 'Activity logging is on.', 'handl-ai-connector-access-control' ),
				'link'       => $link,
				'link_label' => $label,
			);
		}

		return array(
			'status'     => self::STATUS_MISSING,
			'evidence'   => __( 'Activity logging', 'handl-ai-connector-access-control' ),
			'detail'     => __( 'Turn on Activity logging (or Learn mode) so AI events are recorded.', 'handl-ai-connector-access-control' ),
			'link'       => $link,
			'link_label' => $label,
		);
	}

	/**
	 * @param array<string,mixed> $policy Policy.
	 * @return array{status:string,evidence:string,detail:string,link:string,link_label:string}
	 */
	private static function eval_log_retention( array $policy ): array {
		$link  = self::admin_link( Admin::SCREEN_SLUGS['activity'] );
		$label = __( 'Activity keep period', 'handl-ai-connector-access-control' );
		$days  = class_exists( Policy::class, false )
			? Policy::sanitize_log_max_age_days( $policy['log_max_age_days'] ?? null )
			: null;
		$logging = ! empty( $policy['log_enabled'] ) || ! empty( $policy['audit_only'] );
		if ( null !== $days ) {
			return array(
				'status'     => self::STATUS_MET,
				'evidence'   => __( 'Log retention', 'handl-ai-connector-access-control' ),
				'detail'     => sprintf(
					/* translators: %d: keep period in days */
					__( 'Activity keep period is set to %d days.', 'handl-ai-connector-access-control' ),
					$days
				),
				'link'       => $link,
				'link_label' => $label,
			);
		}
		if ( $logging ) {
			return array(
				'status'     => self::STATUS_PARTIAL,
				'evidence'   => __( 'Log retention', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'Logging is on, but the keep period is unbounded. Set a finite Activity keep period.', 'handl-ai-connector-access-control' ),
				'link'       => $link,
				'link_label' => $label,
			);
		}

		return array(
			'status'     => self::STATUS_MISSING,
			'evidence'   => __( 'Log retention', 'handl-ai-connector-access-control' ),
			'detail'     => __( 'No Activity keep period is set. Enable logging and choose how long to keep records.', 'handl-ai-connector-access-control' ),
			'link'       => $link,
			'link_label' => $label,
		);
	}

	/**
	 * @param array<string,mixed> $policy Policy.
	 * @return array{status:string,evidence:string,detail:string,link:string,link_label:string}
	 */
	private static function eval_policy_gate( array $policy ): array {
		$link    = self::admin_link( Admin::SCREEN_SLUGS['rules'] );
		$label   = __( 'Rules', 'handl-ai-connector-access-control' );
		$default = ( ( $policy['default'] ?? 'allow' ) === 'deny' ) ? 'deny' : 'allow';
		$rules   = is_array( $policy['plugins'] ?? null ) ? (array) $policy['plugins'] : array();
		$explicit = 0;
		foreach ( $rules as $rule ) {
			$rule = (string) $rule;
			if ( 'allow' === $rule || 'deny' === $rule ) {
				++$explicit;
			}
		}
		if ( 'deny' === $default ) {
			return array(
				'status'     => self::STATUS_MET,
				'evidence'   => __( 'Policy gate', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'Default policy is Deny — AI use requires an explicit allow.', 'handl-ai-connector-access-control' ),
				'link'       => $link,
				'link_label' => $label,
			);
		}
		if ( $explicit > 0 ) {
			return array(
				'status'     => self::STATUS_PARTIAL,
				'evidence'   => __( 'Policy gate', 'handl-ai-connector-access-control' ),
				'detail'     => sprintf(
					/* translators: %d: count of explicit allow/deny rules */
					__( 'Default is Allow, but %d plugin(s) have an explicit Allow/Deny rule.', 'handl-ai-connector-access-control' ),
					$explicit
				),
				'link'       => $link,
				'link_label' => $label,
			);
		}
		if ( ! empty( $policy['audit_only'] ) ) {
			return array(
				'status'     => self::STATUS_PARTIAL,
				'evidence'   => __( 'Policy gate', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'Learn mode is on — observing AI use without enforcement boundaries.', 'handl-ai-connector-access-control' ),
				'link'       => $link,
				'link_label' => $label,
			);
		}

		return array(
			'status'     => self::STATUS_MISSING,
			'evidence'   => __( 'Policy gate', 'handl-ai-connector-access-control' ),
			'detail'     => __( 'Default is Allow with no explicit plugin rules. Set Deny-by-default or add explicit Allow/Deny rules.', 'handl-ai-connector-access-control' ),
			'link'       => $link,
			'link_label' => $label,
		);
	}

	/**
	 * @return array{status:string,evidence:string,detail:string,link:string,link_label:string}
	 */
	private static function eval_register(): array {
		$link  = self::admin_link( 'handl-aicac-register' );
		$label = __( 'Register', 'handl-ai-connector-access-control' );
		if ( ! class_exists( Register::class, false ) ) {
			return array(
				'status'     => self::STATUS_MISSING,
				'evidence'   => __( 'AI register', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'Provider/connector register is not available in this build yet.', 'handl-ai-connector-access-control' ),
				'link'       => self::admin_link( Admin::MENU_SLUG ),
				'link_label' => __( 'AI Access Control', 'handl-ai-connector-access-control' ),
			);
		}
		if ( Register::is_enabled() ) {
			return array(
				'status'     => self::STATUS_MET,
				'evidence'   => __( 'AI register enabled', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'The AI provider/connector register is on.', 'handl-ai-connector-access-control' ),
				'link'       => $link,
				'link_label' => $label,
			);
		}

		return array(
