	/**
	 * Show AI Act readiness inventory status.
	 *
	 * ## OPTIONS
	 *
	 * [--format=<format>]
	 * : table or json. Default table.
	 *
	 * @when after_wp_load
	 *
	 * @param array<int,string>    $args       Positional.
	 * @param array<string,string> $assoc_args Flags.
	 */
	public function status( $args, $assoc_args ): void {
		unset( $args );
		$settings = Ai_Act::get_settings();
		$rows     = Ai_Act::is_enabled() ? Ai_Act::readiness_roster() : array();
		$counts   = Ai_Act::status_counts( $rows );
		$format   = isset( $assoc_args['format'] ) ? (string) $assoc_args['format'] : 'table';
		$age      = Ai_Act::table_age_ts();

		\WP_CLI::log(
			sprintf(
				'enabled=%s framing=inventory_not_legal_advice met=%d partial=%d not_configured=%d total=%d table_age=%s stale=%s',
				! empty( $settings['enabled'] ) ? 'yes' : 'no',
				(int) $counts['met'],
				(int) $counts['partial'],
				(int) $counts['not_configured'],
				(int) $counts['total'],
				$age > 0 ? gmdate( 'Y-m-d', $age ) : '—',
				Ai_Act::is_table_stale() ? 'yes' : 'no'
			)
		);

		if ( empty( $rows ) ) {
			\WP_CLI::log( 'No obligation rows (feature off or empty table).' );
			if ( (int) $counts['not_configured'] > 0 ) {
				\WP_CLI::error( 'Gaps present: not_configured > 0', false );
			}
			return;
		}

		$display = array();
		foreach ( $rows as $row ) {
			$display[] = array(
				'article'  => (string) $row['article'],
				'id'       => (string) $row['id'],
				'status'   => (string) $row['status'],
				'evidence' => (string) $row['evidence'],
				'label'    => (string) $row['label'],
			);
		}
		if ( 'json' === $format ) {
			\WP_CLI::print_value( $display, array( 'format' => 'json' ) );
		} elseif ( class_exists( '\WP_CLI\Utils' ) ) {
			\WP_CLI\Utils\format_items(
				'table',
				$display,
				array( 'article', 'id', 'status', 'evidence', 'label' )
			);
		} else {
			foreach ( $display as $row ) {
				\WP_CLI::log( implode( "\t", $row ) );
			}
		}

		if ( (int) $counts['not_configured'] > 0 ) {
			\WP_CLI::error(
				sprintf(
					'Gaps present: %d obligation(s) not_configured.',
					(int) $counts['not_configured']
				),
				false
			);
		}
	}

	/**
	 * Export the readiness inventory as CSV.
	 *
	 * ## OPTIONS
	 *
	 * [--porcelain]
	 * : Print CSV only.
	 *
	 * @when after_wp_load
	 *
	 * @param array<int,string>    $args       Positional.
	 * @param array<string,string> $assoc_args Flags.
	 */
	public function export( $args, $assoc_args ): void {
		unset( $args );
		$csv = Ai_Act::csv_for_roster();
		if ( ! empty( $assoc_args['porcelain'] ) ) {
			echo $csv; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI CSV.
			return;
		}
		\WP_CLI::print_value( $csv, array( 'format' => 'csv' ) );
	}
