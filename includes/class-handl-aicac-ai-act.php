				'status'     => self::STATUS_PARTIAL,
				'evidence'   => __( 'Public AI disclosure', 'handl-ai-connector-access-control' ),
				'detail'     => __( 'Machine-readable disclosure JSON is on, but the privacy-policy disclosure is off.', 'handl-ai-connector-access-control' ),
				'link'       => $link,
				'link_label' => $label,
			);
		}

		return array(
			'status'     => self::STATUS_MISSING,
			'evidence'   => __( 'Public AI disclosure', 'handl-ai-connector-access-control' ),
			'detail'     => __( 'Enable public AI disclosure on the privacy policy page (or the shortcode) so people are informed.', 'handl-ai-connector-access-control' ),
			'link'       => $link,
			'link_label' => $label,
		);
